using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace ForbiddenChars;

/// <summary>
/// Generates, for every string field marked with <c>[ForbiddenChars("...")]</c>, a property whose
/// setter throws <see cref="ArgumentException"/> when the value contains any of the given characters.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ForbiddenCharsGenerator : IIncrementalGenerator
{
	const string AttributeFullName = "ForbiddenChars.ForbiddenCharsAttribute";

	const string AttributeSource = """
		// <auto-generated/>
		#nullable enable
		namespace ForbiddenChars
		{
		    /// <summary>
		    /// Generates a property for this string field whose setter rejects values containing any of
		    /// <see cref="Chars"/>. The containing type must be <c>partial</c>.
		    /// </summary>
		    [global::System.AttributeUsage(global::System.AttributeTargets.Field, AllowMultiple = false)]
		    [global::System.Diagnostics.Conditional("FORBIDDEN_CHARS_KEEP_ATTRIBUTE")]
		    internal sealed class ForbiddenCharsAttribute : global::System.Attribute
		    {
		        /// <param name="chars">The characters to reject, e.g. <c>"0O1l"</c>.</param>
		        public ForbiddenCharsAttribute(string chars) => Chars = chars;

		        /// <summary>The characters to reject.</summary>
		        public string Chars { get; }

		        /// <summary>Whether to compare characters case-insensitively (ordinal).</summary>
		        public bool IgnoreCase { get; set; }
		    }
		}
		""";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		context.RegisterPostInitializationOutput(static ctx =>
			ctx.AddSource("ForbiddenCharsAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

		var results = context.SyntaxProvider.ForAttributeWithMetadataName(
			AttributeFullName,
			predicate: static (node, _) => node is VariableDeclaratorSyntax,
			transform: static (ctx, _) => Extract(ctx));

		context.RegisterSourceOutput(
			results.Where(static r => r.Diagnostic is not null).Select(static (r, _) => r.Diagnostic!),
			static (spc, d) => spc.ReportDiagnostic(d.ToDiagnostic()));

		context.RegisterSourceOutput(
			results.Where(static r => r.Target is not null).Select(static (r, _) => r.Target!).Collect(),
			static (spc, targets) => Emit(spc, targets));
	}

	static Result Extract(GeneratorAttributeSyntaxContext ctx)
	{
		var field = (IFieldSymbol)ctx.TargetSymbol;
		var location = ctx.TargetNode.GetLocation();

		if (field.Type.SpecialType != SpecialType.System_String)
			return Result.Error(Diagnostics.FieldMustBeString, location, field.Name);

		var attr = ctx.Attributes[0];
		var chars = attr.ConstructorArguments.Length > 0 ? attr.ConstructorArguments[0].Value as string : null;
		if (string.IsNullOrEmpty(chars))
			return Result.Error(Diagnostics.EmptyChars, location, field.Name);

		var containers = new List<string>();
		for (var type = field.ContainingType; type is not null; type = type.ContainingType)
		{
			if (!IsPartial(type))
				return Result.Error(Diagnostics.TypeMustBePartial, location, type.Name, field.Name);

			containers.Insert(0, Declaration(type));
		}

		var ignoreCase = attr.NamedArguments.FirstOrDefault(kv => kv.Key == "IgnoreCase").Value.Value is true;
		var ns = field.ContainingType.ContainingNamespace;

		return new Result(new Target(
			ns.IsGlobalNamespace ? null : ns.ToDisplayString(),
			string.Join("\n", containers),
			field.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
			field.Name,
			ToPropertyName(field.Name),
			chars!,
			ignoreCase), null);
	}

	static bool IsPartial(INamedTypeSymbol type) =>
		type.DeclaringSyntaxReferences.Any(r =>
			r.GetSyntax() is TypeDeclarationSyntax t && t.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword)));

	static string Declaration(INamedTypeSymbol type)
	{
		var keyword = type.TypeKind switch
		{
			TypeKind.Struct => type.IsRecord ? "record struct" : "struct",
			TypeKind.Interface => "interface",
			_ => type.IsRecord ? "record" : "class",
		};
		var typeParameters = type.TypeParameters.Length == 0
			? ""
			: "<" + string.Join(", ", type.TypeParameters.Select(p => p.Name)) + ">";

		return $"partial {keyword} {type.Name}{typeParameters}";
	}

	static void Emit(SourceProductionContext spc, ImmutableArray<Target> targets)
	{
		foreach (var group in targets.GroupBy(t => t.TypeId))
		{
			var first = group.First();
			var containers = first.Containers.Split('\n');
			var sb = new StringBuilder();

			sb.AppendLine("// <auto-generated/>");
			sb.AppendLine("#nullable enable");
			if (first.Namespace is not null)
				sb.AppendLine($"namespace {first.Namespace}").AppendLine("{");

			foreach (var container in containers)
				sb.AppendLine(container).AppendLine("{");

			foreach (var t in group)
				AppendProperty(sb, t);

			foreach (var _ in containers)
				sb.AppendLine("}");

			if (first.Namespace is not null)
				sb.AppendLine("}");

			spc.AddSource(HintName(first.TypeId), SourceText.From(sb.ToString(), Encoding.UTF8));
		}
	}

	static void AppendProperty(StringBuilder sb, Target t)
	{
		var literal = SymbolDisplay.FormatLiteral(t.Chars, quote: true);
		var lookup = t.IgnoreCase
			? $"{literal}.IndexOf(value[i].ToString(), global::System.StringComparison.OrdinalIgnoreCase)"
			: $"{literal}.IndexOf(value[i])";

		sb.AppendLine($$"""
			/// <summary>
			/// Wraps <see cref="{{t.FieldName}}"/>. Setting a value that contains any of
			/// <c>{{EscapeXml(t.Chars)}}</c> throws <see cref="global::System.ArgumentException"/>.
			/// </summary>
			public string? {{t.PropertyName}}
			{
			    get => {{t.FieldName}};
			    set
			    {
			        if (!(value is null))
			        {
			            for (int i = 0; i < value.Length; i++)
			            {
			                if ({{lookup}} >= 0)
			                {
			                    throw new global::System.ArgumentException(
			                        "'" + value[i] + "' is not allowed (index " + i + ", value \"" + value + "\"). Forbidden characters: " + {{literal}},
			                        nameof(value));
			                }
			            }
			        }
			        {{t.FieldName}} = value;
			    }
			}
			""");
	}

	static string EscapeXml(string s) =>
		s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

	static string HintName(string typeId)
	{
		var sb = new StringBuilder();
		foreach (var c in typeId.Replace("global::", ""))
			sb.Append(char.IsLetterOrDigit(c) || c == '.' ? c : '_');
		return sb.Append(".ForbiddenChars.g.cs").ToString();
	}

	/// <summary>_code / m_code / code → Code</summary>
	static string ToPropertyName(string fieldName)
	{
		var name = fieldName.TrimStart('_');
		if (name.StartsWith("m_", StringComparison.Ordinal))
			name = name.Substring(2);
		return name.Length == 0 ? "Value" : char.ToUpperInvariant(name[0]) + name.Substring(1);
	}

	// Pipeline values hold only strings and value-comparable data so that the incremental
	// generator can cache them; Roslyn symbols would defeat the cache on every keystroke.

	sealed record Target(
		string? Namespace,
		string Containers,
		string TypeId,
		string FieldName,
		string PropertyName,
		string Chars,
		bool IgnoreCase);

	sealed record DiagnosticInfo(DiagnosticDescriptor Descriptor, LocationInfo Location, string Arg0, string? Arg1)
	{
		public Diagnostic ToDiagnostic() =>
			Diagnostic.Create(Descriptor, Location.ToLocation(), Arg1 is null ? [Arg0] : [Arg0, Arg1]);
	}

	sealed record LocationInfo(string FilePath, TextSpan Span, LinePositionSpan LineSpan)
	{
		public static LocationInfo From(Location location) =>
			new(location.SourceTree?.FilePath ?? "", location.SourceSpan, location.GetLineSpan().Span);

		public Location ToLocation() => Location.Create(FilePath, Span, LineSpan);
	}

	sealed record Result(Target? Target, DiagnosticInfo? Diagnostic)
	{
		public static Result Error(DiagnosticDescriptor descriptor, Location location, string arg0, string? arg1 = null) =>
			new(null, new DiagnosticInfo(descriptor, LocationInfo.From(location), arg0, arg1));
	}
}
